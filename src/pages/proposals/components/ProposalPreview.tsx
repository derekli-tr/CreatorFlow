import type { Proposal } from "@/types/proposals";
import StatusBadge from "@/pages/proposals/components/StatusBadge";

interface ProposalPreviewProps {
  proposal: Proposal;
  onToggleEdit: () => void;
}

function renderContent(content: string) {
  return content.split("\n").map((line, i) => {
    const trimmed = line.trim();
    if (trimmed === "") return <div key={i} className="h-3" />;
    if (trimmed.startsWith("## ")) {
      return (
        <h3 key={i} className="font-heading font-semibold text-base text-foreground-900 mt-5 mb-2">
          {trimmed.replace("## ", "")}
        </h3>
      );
    }
    if (/^\d+\./.test(trimmed)) {
      const parts = trimmed.match(/^(\d+)\.\s+(.*)/);
      if (parts) {
        return (
          <div key={i} className="flex gap-2 mb-1.5">
            <span className="text-xs font-bold text-secondary-500 w-5 text-right shrink-0 mt-0.5">{parts[1]}.</span>
            <span className="text-sm text-foreground-700">{parts[2]}</span>
          </div>
        );
      }
    }
    if (trimmed.startsWith("- ")) {
      return (
        <div key={i} className="flex gap-2 mb-1 ml-4">
          <span className="text-xs text-foreground-400 shrink-0 mt-1">&bull;</span>
          <span className="text-sm text-foreground-700">{trimmed.replace("- ", "")}</span>
        </div>
      );
    }
    return (
      <p key={i} className="text-sm text-foreground-700 leading-relaxed mb-1">
        {trimmed}
      </p>
    );
  });
}

export default function ProposalPreview({ proposal, onToggleEdit }: ProposalPreviewProps) {
  const cover = proposal.sections.find((s) => s.type === "cover");
  const bodySections = proposal.sections.filter((s) => s.type !== "cover");

  return (
    <div className="max-w-3xl mx-auto space-y-6">
      {/* Actions bar */}
      <div className="flex items-center justify-between">
        <button
          onClick={onToggleEdit}
          className="inline-flex items-center gap-1.5 px-4 py-2 rounded-lg border border-background-200 text-sm font-medium text-foreground-600 hover:bg-background-50 transition-colors cursor-pointer whitespace-nowrap"
        >
          <span className="w-4 h-4 flex items-center justify-center">
            <i className="ri-edit-line" />
          </span>
          Back to Editor
        </button>
        <StatusBadge status={proposal.status} />
      </div>

      {/* Cover page */}
      <div className="bg-white rounded-xl border border-background-200 shadow-ambient overflow-hidden">
        <div className="bg-background-100 px-8 py-8 border-b border-background-200">
          <p className="text-xs font-semibold text-foreground-400 uppercase tracking-widest mb-6">Proposal</p>
          <h1 className="font-heading font-bold text-2xl text-foreground-950 leading-tight max-w-lg">
            {proposal.title}
          </h1>
          <div className="mt-8 grid grid-cols-1 sm:grid-cols-2 gap-4 text-sm">
            <div>
              <p className="text-xs font-semibold text-foreground-400 uppercase tracking-wider mb-1">Prepared For</p>
              <p className="font-semibold text-foreground-900">{proposal.coverData.clientName}</p>
              <p className="text-foreground-500">{proposal.coverData.clientCompany}</p>
            </div>
            <div>
              <p className="text-xs font-semibold text-foreground-400 uppercase tracking-wider mb-1">Prepared By</p>
              <p className="font-semibold text-foreground-900">{proposal.coverData.preparedBy}</p>
              <p className="text-foreground-500">{proposal.coverData.preparedCompany}</p>
            </div>
          </div>
          <div className="mt-4 flex items-center gap-6 text-xs text-foreground-400">
            <span>Date: {new Date(proposal.coverData.date).toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" })}</span>
            <span>Valid until: {new Date(proposal.coverData.validUntil).toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" })}</span>
          </div>
        </div>

        {/* Body sections */}
        <div className="p-8 space-y-8">
          {bodySections.map((section) => (
            <div key={section.type}>
              <h2 className="font-heading font-bold text-lg text-foreground-950 mb-3 pb-2 border-b border-background-100">
                {section.label}
              </h2>
              <div className="prose-content">{renderContent(section.content)}</div>
            </div>
          ))}
        </div>

        {/* Footer */}
        <div className="border-t border-background-200 px-8 py-4 flex items-center justify-between text-xs text-foreground-400">
          <span>Generated by FreelanceFlow &mdash; {new Date().toLocaleDateString()}</span>
          <span className="font-medium text-foreground-900">Total: ${proposal.amount.toLocaleString()}</span>
        </div>
      </div>
    </div>
  );
}